/** The four colour schemes offered at character creation. */
export const SCHEMES = [
  { name: 'BONE', body: '#d0d0c8' },
  { name: 'BLOOD', body: '#c04040' },
  { name: 'MOSS', body: '#6a9a4a' },
  { name: 'STEEL', body: '#6a8ac0' },
];

const playerCache = new Map<string, Art>();

export function playerArt(cls: ClassId, scheme: number, facing: Dir): { art: Art; flip: boolean } {
  const view: View = facing === 'down' ? 'front' : facing === 'up' ? 'back' : 'side';
  const key = `${cls}:${scheme}:${view}`;
  let a = playerCache.get(key);
  if (!a) {
    a = mono((SCHEMES[scheme] ?? SCHEMES[0]).body, PLAYER_GRIDS[cls][view]);
    playerCache.set(key, a);
  }
  return { art: a, flip: facing === 'left' };
}

