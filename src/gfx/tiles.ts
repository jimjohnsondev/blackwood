/** Grass alternates between two patterns so fields don't look tiled. */
export function tileArt(tile: T, x: number, y: number): Art {
  if (tile === T.Grass) return (x * 7 + y * 13) % 3 ? grassA : grassB;
  return TILE_ART[tile];
}

export function siteArt(kind: SiteKind): Art {
  return SITE_ART[kind];
}

/** Ground textures flip on alternate tiles; water also shimmers over time. */
export function tileFlip(tile: T, x: number, y: number, frame: number): boolean {
  if (tile === T.Ocean || tile === T.Water || tile === T.Shallows) return (x * 3 + y + frame) % 2 === 0;
  if (tile === T.Grass || tile === T.Mire || tile === T.Dirt || tile === T.Scrub || tile === T.CaveFloor) {
    return (x + y) % 2 === 0;
  }
  if (tile === T.Pine || tile === T.DeadWood || tile === T.Hills || tile === T.CaveWall) return (x * 5 + y * 3) % 2 === 0;
  return false;
}
